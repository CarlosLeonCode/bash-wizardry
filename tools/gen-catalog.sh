#!/usr/bin/env bash
#
# Generates the website's command list from the catalog.
#
#   catalog/commands.tsv     (module, name, kind, usage, English description)
#   catalog/commands.es.tsv  (name, Spanish description; same names, same order)
#     ->  web/src/lib/catalog.generated.ts
#
# Development tooling only (not on the user's PATH). CI regenerates the file
# and fails if the committed copy differs, so run this after editing a TSV.
# Fails when a command lacks a Spanish row or the Spanish file has an extra,
# unknown, duplicated or out-of-order one.
# Usage: bash tools/gen-catalog.sh [output_path]

set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
src="$root/catalog/commands.tsv"
src_es="$root/catalog/commands.es.tsv"
out="${1:-$root/web/src/lib/catalog.generated.ts}"
tmp="$out.tmp.$$"
trap 'rm -f "$tmp"' EXIT

# An empty first file would make awk treat commands.tsv as the Spanish one.
[ -s "$src_es" ] || { echo "gen-catalog: missing or empty $src_es" >&2; exit 1; }

LC_ALL=C awk -F '\t' '
    function jesc(s,   out, i, c) {
        out = ""
        for (i = 1; i <= length(s); i++) {
            c = substr(s, i, 1)
            if (c == "\\" || c == "\"") out = out "\\" c
            else out = out c
        }
        return out
    }
    function fail(msg) {
        printf "gen-catalog: %s\n", msg > "/dev/stderr"
        failed = 1
    }

    # ---- pass 1: catalog/commands.es.tsv ---------------------------------
    FNR == NR {
        if (FNR == 1) {
            if ($0 != "name\tdescription") fail("commands.es.tsv: bad header, expected name<TAB>description")
            next
        }
        if ($0 == "") next
        if (NF != 2) { fail(sprintf("commands.es.tsv line %d has %d fields, expected 2", FNR, NF)); next }
        if ($1 == "" || $2 == "") { fail(sprintf("commands.es.tsv line %d: empty name or description", FNR)); next }
        if ($1 in es) { fail(sprintf("commands.es.tsv line %d: duplicate name %s", FNR, $1)); next }
        es[$1] = $2
        es_order[++es_count] = $1
        next
    }

    # ---- pass 2: catalog/commands.tsv ------------------------------------
    FNR == 1 {
        print "// Generated by tools/gen-catalog.sh from catalog/commands.tsv and"
        print "// catalog/commands.es.tsv. Do not edit."
        print ""
        print "export type CatalogKind = \"alias\" | \"function\" | \"script\";"
        print ""
        print "export type CatalogLocale = \"en\" | \"es\";"
        print ""
        print "export interface CatalogEntry {"
        print "  readonly module: string;"
        print "  readonly name: string;"
        print "  readonly kind: CatalogKind;"
        print "  /** How to call it; falls back to the name. */"
        print "  readonly usage: string;"
        print "  /** One line per locale. Only the English one carries \"Asks first.\". */"
        print "  readonly description: Readonly<Record<CatalogLocale, string>>;"
        print "}"
        print ""
        print "export const CATALOG: readonly CatalogEntry[] = ["
        next
    }
    $0 == "" { next }
    NF != 5 {
        fail(sprintf("commands.tsv line %d has %d fields, expected 5", FNR, NF))
        next
    }
    {
        row++
        seen[$2] = 1
        if (!($2 in es)) {
            fail(sprintf("no Spanish description for %s: add a row to catalog/commands.es.tsv", $2))
            next
        }
        # Report only the first order mismatch; later rows would all cascade.
        if (es_order[row] != $2 && !misordered++) {
            fail(sprintf("commands.es.tsv row %d is %s, expected %s (keep the order of commands.tsv)", row, es_order[row], $2))
        }
        printf "  { module: \"%s\", name: \"%s\", kind: \"%s\", usage: \"%s\", description: { en: \"%s\", es: \"%s\" } },\n", \
            jesc($1), jesc($2), jesc($3), jesc($4 == "" ? $2 : $4), jesc($5), jesc(es[$2])
    }
    END {
        for (i = 1; i <= es_count; i++) {
            if (!(es_order[i] in seen)) fail(sprintf("commands.es.tsv has unknown name %s (not in catalog/commands.tsv)", es_order[i]))
        }
        if (failed) exit 1
        print "] as const;"
    }
' "$src_es" "$src" > "$tmp"

mv "$tmp" "$out"
trap - EXIT
echo "Wrote $out"
